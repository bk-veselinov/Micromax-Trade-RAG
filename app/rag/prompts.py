SOURCE_LABEL = {
    "product": "продукт",
    "category": "категория",
    "service": "услуга",
    "knowledge": "фирмена информация",
}


def format_context(hits) -> str:
    """Numbered blocks: [n] (type) title, link, text."""
    blocks = []
    for i, h in enumerate(hits, start=1):
        meta = h.metadata
        head = f"[{i}] ({SOURCE_LABEL.get(meta['type'], meta['type'])}) {meta.get('title', '')}"
        if meta.get("permalink"):
            head += f"\nЛинк: {meta['url']}"
        blocks.append(f"{head}\n{h.text}")
    return "\n\n---\n\n".join(blocks)


def user_prompt(question: str, context: str) -> str:
    return f"Контекст:\n\n{context}\n\n===\n\nВъпрос: {question}"
